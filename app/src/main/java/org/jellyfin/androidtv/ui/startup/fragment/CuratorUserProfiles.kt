/**
 * How a Jellyfin user is presented on the "Who's watching?" screen.
 * [avatar] is a flat vector drawn on top of the [gradient]; null falls back to the
 * user's Jellyfin profile image, then their initial.
 */
data class CuratorUserProfile(
	val displayName: String,
	@DrawableRes val avatar: Int?,
	val gradient: List<Color>,
	val order: Int,
)

// Avatar vectors are generated by design/curator-avatars.py — keep the gradients here in sync with it
private val knownProfiles = mapOf(
	"pthek" to CuratorUserProfile("Dad", R.drawable.avatar_pthek, listOf(Color(0xFF1E3C72), Color(0xFF2A9D8F)), 0),
	"jthek" to CuratorUserProfile("Mam", R.drawable.avatar_jthek, listOf(Color(0xFFB5179E), Color(0xFFF72585)), 1),
	"admin" to CuratorUserProfile("Chris", R.drawable.avatar_admin, listOf(Color(0xFFAA5CC3), Color(0xFF00A4DC)), 2),
	"gemma" to CuratorUserProfile("Gemma", R.drawable.avatar_gemma, listOf(Color(0xFFFF6B6B), Color(0xFFFFA94D)), 3),
	"steven" to CuratorUserProfile("Stephen", R.drawable.avatar_steven, listOf(Color(0xFF0F766E), Color(0xFF65A30D)), 4),
)

private val kidsProfile = CuratorUserProfile("Kids", R.drawable.avatar_kids, listOf(Color(0xFFFFD60A), Color(0xFFFF8C42)), Int.MAX_VALUE)

private val fallbackGradients = listOf(
	listOf(Color(0xFF1565C0), Color(0xFF42A5F5)),
	listOf(Color(0xFF2E7D32), Color(0xFF66BB6A)),
	listOf(Color(0xFF6A1B9A), Color(0xFFAB47BC)),
	listOf(Color(0xFFC62828), Color(0xFFEF5350)),
	listOf(Color(0xFFE65100), Color(0xFFFFA726)),
	listOf(Color(0xFF00838F), Color(0xFF26C6DA)),
)

fun curatorUserProfile(username: String): CuratorUserProfile {
	if (isKidsUser(username)) return kidsProfile
	knownProfiles[username.lowercase()]?.let { return it }

	// Unknown users sit between the family and Kids, alphabetically via the stable sort
	return CuratorUserProfile(
		displayName = username.replaceFirstChar { it.uppercase() },
		avatar = null,
		gradient = fallbackGradients[username.hashCode().absoluteValue % fallbackGradients.size],
		order = knownProfiles.size,
	)
}

/**
 * The round avatar for a profile: its vector on the gradient, or the profile image over its initial.
 */
@Composable
fun CuratorAvatar(
	profile: CuratorUserProfile,
	imageUrl: String?,
	modifier: Modifier = Modifier,
	initialFontSize: Int = 48,
) {
	Box(
		modifier = modifier
			.clip(CircleShape)
			.background(Brush.linearGradient(profile.gradient)),
		contentAlignment = Alignment.Center,
	) {
		if (profile.avatar != null) {
			Image(
				painter = painterResource(profile.avatar),
				contentDescription = null,
				modifier = Modifier.fillMaxSize(),
			)
		} else {
			// Initial always rendered underneath — shows through if the profile image fails to load
			Text(
				text = profile.displayName.firstOrNull()?.uppercase() ?: "?",
				color = Color.White,
				fontSize = initialFontSize.sp,
				fontWeight = FontWeight.Bold,
			)
			if (imageUrl != null) {
				AsyncImage(
					modifier = Modifier.fillMaxSize(),
					scaleType = ImageView.ScaleType.CENTER_CROP,
					url = imageUrl,
				)
			}
		}
	}
}
